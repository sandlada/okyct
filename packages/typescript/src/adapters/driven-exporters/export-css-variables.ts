
import {
  StandardTones,
  StandardPaletteKeys,
  SystemColorTokens,
  CssSchemeModes,
  type CssSchemeMode,
  type DynamicSchemeColors,
  type ResolvedCustomColor,
} from '../../ports/index.ts'
import type { PaletteSet } from '../../application/index.ts'
import { kebabCase } from './internal/kebab-case.ts'

export { CssSchemeModes, type CssSchemeMode }

const customTuple = (color: ResolvedCustomColor) => {
  const k = kebabCase(color.name)
  return [
    [`--md-custom-color-${k}`, color.color],
    [`--md-custom-color-on-${k}`, color.onColor],
    [`--md-custom-color-${k}-container`, color.colorContainer],
    [`--md-custom-color-on-${k}-container`, color.onColorContainer],
  ] as const
}

export function exportCssVariables(
  lightScheme: DynamicSchemeColors,
  darkScheme: DynamicSchemeColors,
  palettes: PaletteSet,
  customColorsLight: ResolvedCustomColor[] = [],
  customColorsDark: ResolvedCustomColor[] = [],
  schemeMode: CssSchemeMode = 'light-dark'
): string {
  const formatEntries = (scheme: DynamicSchemeColors, indent = '  ') => {
    return SystemColorTokens
      .map((key) => `${indent}--md-sys-color-${kebabCase(key)}: ${scheme[key]};`)
      .join('\n')
  }

  const formatCustomEntries = (customs: ResolvedCustomColor[], indent = '  ') => {
    if (customs.length === 0) return ''
    const lines = customs.flatMap((c) => customTuple(c).map(([name, value]) => `${indent}${name}: ${value};`))
    return `\n\n  /* -------------------------------------------------------------\n     Custom Extended Semantic Colors (4-Tuple)\n     ------------------------------------------------------------- */\n${lines.join('\n')}`
  }

  const paletteEntries = (indent = '  ') => {
    const list: string[] = []
    for (const key of StandardPaletteKeys) {
      for (const t of StandardTones) {
        list.push(`${indent}--md-ref-palette-${kebabCase(key)}-${t}: ${palettes[key].tone(t)};`)
      }
    }
    return list.join('\n')
  }

  const header = `/* ==========================================================================
   Generated by OKYCT Studio (Production Design Tokens)
   ========================================================================== */`

  const paletteBlock = `  /* -------------------------------------------------------------
     Reference Tonal Palettes (13 Standard Stops)
     ------------------------------------------------------------- */
${paletteEntries('  ')}`

  if (schemeMode === 'light-dark') {
    const darkByName = new Map(customColorsDark.map((color) => [color.name, color]))
    const systemLines = SystemColorTokens
      .map((key) => `  --md-sys-color-${kebabCase(key)}: light-dark(${lightScheme[key]}, ${darkScheme[key]});`)
      .join('\n')
    const customLines = customColorsLight.flatMap((color) => {
      const dark = darkByName.get(color.name) ?? color
      const darkSlots = customTuple(dark)
      return customTuple(color).map(([name, value], index) => `  ${name}: light-dark(${value}, ${darkSlots[index][1]});`)
    })
    const customBlock = customLines.length === 0
      ? ''
      : `\n\n  /* -------------------------------------------------------------\n     Custom Extended Semantic Colors (4-Tuple)\n     ------------------------------------------------------------- */\n${customLines.join('\n')}`

    return `${header}

:root {
  color-scheme: light dark;

${paletteBlock}

  /* -------------------------------------------------------------
     System Colors — light-dark(light, dark)
     ------------------------------------------------------------- */
${systemLines}${customBlock}
}
`
  }

  return `${header}

:root {
${paletteBlock}
}

.light {
  /* -------------------------------------------------------------
     Light Scheme System Colors
     ------------------------------------------------------------- */
${formatEntries(lightScheme, '  ')}${formatCustomEntries(customColorsLight, '  ')}
}

.dark {
  /* -------------------------------------------------------------
     Dark Scheme System Colors
     ------------------------------------------------------------- */
${formatEntries(darkScheme, '  ')}${formatCustomEntries(customColorsDark, '  ')}
}
`
}
