import {
  STANDARD_TONES,
  StandardPaletteKeys,
  SystemColorTokens,
  type SystemColorToken,
  type DynamicSchemeColors,
  type ResolvedCustomColor,
  type ITokenExporterPort,
} from '../../ports/index.ts'
import type { PaletteSet, TonalPalette } from '../../application/index.ts'

function stripTones(scheme: DynamicSchemeColors): Record<SystemColorToken, string> {
  const result = {} as Record<SystemColorToken, string>
  for (const key of SystemColorTokens) {
    result[key] = scheme[key]
  }
  return result
}

function kebabCase(str: string): string {
  return str.replace(/([a-z0-9]|(?=[A-Z]))([A-Z])/g, '$1-$2').toLowerCase()
}

export function exportCssVariables(
  lightScheme: DynamicSchemeColors,
  darkScheme: DynamicSchemeColors,
  palettes: PaletteSet,
  customColorsLight: ResolvedCustomColor[] = [],
  customColorsDark: ResolvedCustomColor[] = []
): string {
  const formatEntries = (scheme: DynamicSchemeColors, indent = '  ') => {
    return SystemColorTokens
      .map((key) => `${indent}--md-sys-color-${kebabCase(key)}: ${scheme[key]};`)
      .join('\n')
  }

  const formatCustomEntries = (customs: ResolvedCustomColor[], indent = '  ') => {
    if (customs.length === 0) return ''
    const lines = customs.flatMap((c) => {
      const k = kebabCase(c.name)
      return [
        `${indent}--md-custom-color-${k}: ${c.color};`,
        `${indent}--md-custom-color-on-${k}: ${c.onColor};`,
        `${indent}--md-custom-color-${k}-container: ${c.colorContainer};`,
        `${indent}--md-custom-color-on-${k}-container: ${c.onColorContainer};`,
      ]
    })
    return `\n\n  /* -------------------------------------------------------------\n     Custom Extended Semantic Colors (4-Tuple)\n     ------------------------------------------------------------- */\n${lines.join('\n')}`
  }

  const paletteEntries = (indent = '  ') => {
    const list: string[] = []
    for (const key of StandardPaletteKeys) {
      for (const t of STANDARD_TONES) {
        list.push(`${indent}--md-ref-palette-${kebabCase(key)}-${t}: ${palettes[key].tone(t)};`)
      }
    }
    return list.join('\n')
  }

  return `/* ==========================================================================
   Generated by OKYCT Studio (Production Design Tokens)
   ========================================================================== */

:root {
  /* -------------------------------------------------------------
     Reference Tonal Palettes (13 Standard Stops)
     ------------------------------------------------------------- */
${paletteEntries('  ')}

  /* -------------------------------------------------------------
     Light Scheme System Colors
     ------------------------------------------------------------- */
${formatEntries(lightScheme, '  ')}${formatCustomEntries(customColorsLight, '  ')}
}

.dark {
  /* -------------------------------------------------------------
     Dark Scheme System Colors
     ------------------------------------------------------------- */
${formatEntries(darkScheme, '  ')}${formatCustomEntries(customColorsDark, '  ')}
}
`
}

export function exportTailwindV4(
  lightScheme: DynamicSchemeColors,
  darkScheme: DynamicSchemeColors,
  customColorsLight: ResolvedCustomColor[] = []
): string {
  void lightScheme
  void darkScheme

  const systemLines = SystemColorTokens
    .map((key) => {
      const k = kebabCase(key)
      return `  --color-${k}: var(--md-sys-color-${k});`
    })
    .join('\n')

  const customLines = customColorsLight
    .flatMap((c) => {
      const k = kebabCase(c.name)
      return [
        `  --color-${k}: var(--md-custom-color-${k});`,
        `  --color-on-${k}: var(--md-custom-color-on-${k});`,
        `  --color-${k}-container: var(--md-custom-color-${k}-container);`,
        `  --color-on-${k}-container: var(--md-custom-color-on-${k}-container);`,
      ]
    })
    .join('\n')

  return `/* Tailwind CSS v4 Theme Extension */
@import "tailwindcss";
@custom-variant dark (&:where(.dark, .dark *));

@theme {
${systemLines}${customLines ? `\n\n  /* Custom Extended Semantic Tokens */\n${customLines}` : ''}
}
`
}

export function exportW3cDesignTokens(
  lightScheme: DynamicSchemeColors,
  darkScheme: DynamicSchemeColors,
  customColorsLight: ResolvedCustomColor[] = [],
  customColorsDark: ResolvedCustomColor[] = []
): string {
  const buildGroup = (scheme: DynamicSchemeColors, customs: ResolvedCustomColor[]) => {
    const group: Record<string, any> = {}
    for (const k of SystemColorTokens) {
      group[k] = {
        $value: scheme[k],
        $type: 'color',
        $description: `Material Design 3 system token for ${k}`,
      }
    }
    for (const c of customs) {
      group[c.name] = {
        color: { $value: c.color, $type: 'color', $description: `${c.label} base role` },
        onColor: { $value: c.onColor, $type: 'color', $description: `${c.label} foreground text` },
        colorContainer: { $value: c.colorContainer, $type: 'color', $description: `${c.label} tonal container` },
        onColorContainer: { $value: c.onColorContainer, $type: 'color', $description: `${c.label} container text` },
      }
    }
    return group
  }

  const tokens = {
    color: {
      light: buildGroup(lightScheme, customColorsLight),
      dark: buildGroup(darkScheme, customColorsDark),
    },
  }

  return JSON.stringify(tokens, null, 2)
}

export function exportTypeScriptTokens(
  lightScheme: DynamicSchemeColors,
  darkScheme: DynamicSchemeColors,
  customColorsLight: ResolvedCustomColor[] = [],
  customColorsDark: ResolvedCustomColor[] = []
): string {
  const buildCustomMap = (customs: ResolvedCustomColor[]) => {
    const res: Record<string, { color: string; onColor: string; colorContainer: string; onColorContainer: string }> = {}
    for (const c of customs) {
      res[c.name] = {
        color: c.color,
        onColor: c.onColor,
        colorContainer: c.colorContainer,
        onColorContainer: c.onColorContainer,
      }
    }
    return res
  }

  return `/**
 * OKYCT Typed Color Tokens
 */

export const LightThemeTokens = ${JSON.stringify(
    { ...stripTones(lightScheme), custom: buildCustomMap(customColorsLight) },
    null,
    2
  )} as const

export const DarkThemeTokens = ${JSON.stringify(
    { ...stripTones(darkScheme), custom: buildCustomMap(customColorsDark) },
    null,
    2
  )} as const

export type ThemeColors = typeof LightThemeTokens
`
}

export class MultiFormatTokenExporterAdapter implements ITokenExporterPort<TonalPalette> {
  exportCssVariables = exportCssVariables
  exportTailwindV4 = exportTailwindV4
  exportW3cDesignTokens = exportW3cDesignTokens
  exportTypeScriptTokens = exportTypeScriptTokens
}
